const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync(require('node:path').join(__dirname,'../dashboard.html'),'utf8');
const scripts=[...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
const sample='1630,-2.75,1.19,360.00,-0.06,-0.12,-0.06,-0.52,-0.23,10.21,0,0,0,0,OK';
test('CSV: valid values, invalid readings and corrupt payloads',()=>{
  const c=vm.createContext({});vm.runInContext(scripts[0],c);
  const parse=line=>c.parseLine(line);
  assert.equal(parse(sample).roll,-2.75);
  assert.equal(parse(sample).accel[2],10.21);
  for(const s of [sample.replace('-2.75','NaN'),sample.replace('1.19',''),sample.replace(',0,OK',',4,OK'),sample.replace('OK','INVALID')])assert.equal(parse(s).kind,'invalid');
  assert.equal(parse('# RAW Euler=0,0,0').kind,'log');
  assert.equal(parse('ts_ms,roll_deg,pitch_deg').kind,'log');
  const lines=[];const feed=c.lineBuffer(l=>lines.push(l));
  feed(sample.slice(0,20));assert.equal(lines.length,0);
  feed(sample.slice(20)+'\r\n# STATUS ok\npartial');
  assert.deepEqual(lines,[sample,'# STATUS ok']);
  feed('x'.repeat(5000));assert.match(lines.at(-1),/oversized/);
});
test('USB lifecycle, duplicate samples, invalidation and stale display',async()=>{
  let now=0,tick,closed=false;
  const elements=new Map();
  const element=id=>{
    if(!elements.has(id))elements.set(id,{textContent:'',disabled:false,className:'',style:{},classList:{add(){},remove(){}},clientWidth:600,clientHeight:200,getContext:()=>new Proxy({},{get:()=>()=>{}})});
    return elements.get(id);
  };
  const port={readable:new ReadableStream({start(controller){controller.enqueue(new TextEncoder().encode(sample+'\n'));}}),async open(options){assert.equal(options.baudRate,115200);},async close(){closed=true;}};
  const c=vm.createContext({document:{getElementById:element},navigator:{serial:{requestPort:async()=>port}},window:{isSecureContext:true,devicePixelRatio:1},performance:{now:()=>now},setInterval:fn=>{tick=fn;},TextDecoder,console});
  scripts.forEach(s=>vm.runInContext(s,c));
  await element('connect').onclick();await new Promise(resolve=>setImmediate(resolve));
  assert.equal(element('roll').textContent,'-2.75');
  vm.runInContext(`receive(${JSON.stringify(sample)})`,c);
  assert.equal(element('counts').textContent,'1 / 0 / 0');
  now=600;tick();assert.equal(element('roll').textContent,'—');
  assert.equal(element('state').textContent,'Sin muestra reciente');
  vm.runInContext(`receive(${JSON.stringify(sample.replace('1630','1730'))})`,c);
  assert.equal(element('roll').textContent,'-2.75');
  vm.runInContext(`receive(${JSON.stringify(sample.replace('OK','INVALID'))})`,c);
  assert.equal(element('roll').textContent,'—');
  assert.equal(element('state').textContent,'Lectura inválida');
  await element('disconnect').onclick();
  assert.equal(closed,true);assert.equal(element('state').textContent,'Desconectado');
  assert.equal(element('connect').disabled,false);
});
